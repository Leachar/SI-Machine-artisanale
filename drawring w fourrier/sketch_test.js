// Définissez ici la source de données à utiliser :
const activeDrawingData = lionPoints; 

// Coefficient multiplicateur (indispensable pour les données scientifiques du lion)
const scaleFactor = 6000; 
// Sauter des points (skip) pour alléger le calcul. 1 = tous les points
const skipPoints = 1; 


// ==========================================
// 3. VARIABLES GLOBALES ET ALGORITHME
// ==========================================

let x = [];
let fourierX;
let time = 0;
let path = [];
let completedPath = [];
let isDrawingComplete = false; // Corrigé : 'false' au lieu de 'flase'

function setup() {
  createCanvas(800, 600);
  
  // Boucle d'initialisation adaptée pour gérer différents formats de tableaux
  for (let i = 0; i < activeDrawingData.length; i += skipPoints) {
    let px, py;
    
    // Détection automatique du format des données (tableau de tableaux vs objets x/y)
    if (Array.isArray(activeDrawingData[i])) {
      px = activeDrawingData[i][0];
      py = activeDrawingData[i][1];
    } else {
      px = activeDrawingData[i].x;
      py = activeDrawingData[i].y;
    }
    
    // Applique le facteur d'échelle lors de la création du nombre complexe
    const c = new Complex(px * scaleFactor, py * scaleFactor);
    x.push(c);
  }
  
  fourierX = dft(x);
  fourierX.sort((a, b) => b.amp - a.amp);
}

function epicycles(x, y, rotation, fourier) {
  // Option pour limiter le nombre d'épicycles (et donc la précision/complexité)
  const maxCercles = fourier.length; // Mettez une valeur fixe comme 50 pour simplifier le dessin
  const nbCercles = min(maxCercles, fourier.length);
  
  for (let i = 0; i < nbCercles; i++) {
    let prevx = x;
    let prevy = y;
    let freq = fourier[i].freq;
    let radius = fourier[i].amp;
    let phase = fourier[i].phase;
    
    x += radius * cos(freq * time + phase + rotation);
    y += radius * sin(freq * time + phase + rotation);

    stroke(255, 100);
    noFill();
    ellipse(prevx, prevy, radius * 2);
    
    stroke(255);
    line(prevx, prevy, x, y);
  }
  return createVector(x, y);
}

function draw() {
  background(0);

  // Calcule le nouveau point de la trajectoire
  if (!isDrawingComplete) {
    let v = epicycles(width / 2, height / 2, 0, fourierX);
    path.unshift(v);
  } else {
    // Une fois terminé, on peut soit figer le système, soit redessiner le tracé final
    // (Dans cette version on n'anime plus les épicycles une fois fini)
  }

  // Dessine la trajectoire mémorisée
  beginShape();
  noFill();
  stroke(255, 0, 0); // Couleur du trait (rouge)
  strokeWeight(2);
  let renderPath = isDrawingComplete ? completedPath : path;
  for (let i = 0; i < renderPath.length; i++) {
    vertex(renderPath[i].x, renderPath[i].y);
  }
  endShape();

  // Avance le temps
  const dt = TWO_PI / fourierX.length;
  time += dt;

  // Condition de fin de boucle
  if (time > TWO_PI && !isDrawingComplete) { // Le '!isDrawingComplete' évite de déclencher la console à chaque frame
    isDrawingComplete = true; // Corrigé : 'true' au lieu de 'True'
    completedPath = [...path];
    console.log("Dessin terminé ! Nombre de points enregistrés :", completedPath.length);
  }
}