import numpy as np
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle

def compute_precision(x0, y0, L, omega, phi, mode, display_plot=False):
    """
    Calcule la précision d'un dessin généré par un système mécanique
    (superposition de barres rotatives) en le comparant à une forme
    de référence discrétisée sur une grille.

    Entrées :
    x0, y0 : float
        Position du centre
    L : float ou array
        Longueurs des barres.
    omega : float ou array
        Pulsations des barres.
    phi : float ou array
        Phases initiales.
    mode : int
        Identifiant de la forme de référence à comparer.
        0 : Cadre
        1 : Lion
        2 : Abeilles
        3 : Engrenages
    display_plot : bool
        Affiche ou non les cases vertes/rouges.

    Sortie :
    precision : float
        Taux de recouvrement entre la trajectoire générée
        et la forme de référence (Intersection / Union).

    Notes :
    - La grille utilisée pour la discrétisation a un pas fixe de 0.0012.
    - Toute cellule traversée par un segment est comptée (rasterisation
      type Amanatides & Woo, "supercover").
    """
    
    grid_size = 0.0012

    # 1. trajectoire générée
    L     = np.atleast_1d(L)
    omega = np.atleast_1d(omega)
    phi   = np.atleast_1d(phi)
    t = np.linspace(0, 1, 10000)
    traj_x = np.full_like(t, x0, dtype=float)
    traj_y = np.full_like(t, y0, dtype=float)
    for j in range(len(L)):
        traj_x += L[j] * np.cos(omega[j] * t + phi[j])
        traj_y += L[j] * np.sin(omega[j] * t + phi[j])

    # 2. rasterisation de la trajectoire
    traj_cells = set()
    for k in range(len(traj_x) - 1):
        traj_cells |= cells_for_segment((traj_x[k], traj_y[k]),
                                        (traj_x[k+1], traj_y[k+1]),
                                        grid_size)

    # 3. rasterisation de la référence
    ref_curves = _get_reference_matrices(mode)
    ref_cells = set()

    for ref in ref_curves:
        rx, ry = ref[:,0], ref[:,1]
        for i in range(len(rx) - 1):
            ref_cells |= cells_for_segment((rx[i], ry[i]),
                                           (rx[i+1], ry[i+1]),
                                           grid_size)

    # 4. précision (IoU)
    green = traj_cells & ref_cells
    red   = traj_cells ^ ref_cells

    n_green = len(green)
    n_red   = len(red)

    precision = n_green / (n_green + n_red) if (n_green + n_red) else 0.0

    # 5. affichage
    if display_plot:
        _plot_precision(green, red, grid_size, ref_curves,
                        traj_x, traj_y, precision, n_green, n_red)

    return precision

def cells_for_segment(p0, p1, grid_size=0.0012):
    """
    Retourne toutes les cellules (i, j) traversées par le segment p0 -> p1
    en utilisant une rasterisation de type Amanatides & Woo (supercover).
    """
    x0, y0 = p0
    x1, y1 = p1
    g = grid_size

    # Coordonnées en unités de grille (avec décalage demi-case)
    gx0, gy0 = (x0 + g/2) / g, (y0 + g/2) / g
    gx1, gy1 = (x1 + g/2) / g, (y1 + g/2) / g

    ix,  iy  = int(np.floor(gx0)), int(np.floor(gy0))
    ix1, iy1 = int(np.floor(gx1)), int(np.floor(gy1))

    cells = {(ix, iy)}

    if ix == ix1 and iy == iy1:
        return cells

    dx = gx1 - gx0
    dy = gy1 - gy0

    step_x = 1 if dx > 0 else -1 if dx < 0 else 0
    step_y = 1 if dy > 0 else -1 if dy < 0 else 0

    # Temps de traversée vers la frontière suivante
    if step_x != 0:
        next_boundary_x = ix + (1 if step_x > 0 else 0)
        tMaxX   = (next_boundary_x - gx0) / dx
        tDeltaX = step_x / dx
    else:
        tMaxX = tDeltaX = np.inf

    if step_y != 0:
        next_boundary_y = iy + (1 if step_y > 0 else 0)
        tMaxY   = (next_boundary_y - gy0) / dy
        tDeltaY = step_y / dy
    else:
        tMaxY = tDeltaY = np.inf

    # Parcours de toutes les cases jusqu'à la case d'arrivée
    while ix != ix1 or iy != iy1:
        if tMaxX < tMaxY:
            ix += step_x
            tMaxX += tDeltaX
        else:
            iy += step_y
            tMaxY += tDeltaY
        cells.add((ix, iy))

    return cells

def _plot_precision(green_cells, red_cells, grid_size, ref_curves,
                   traj_x, traj_y, precision, n_green, n_red):
    """Affiche la précision avec cellules vertes et rouges"""
    
    fig, ax = plt.subplots(figsize=(12, 10))
    
    # Cellules rouges (différence)
    for (i, j) in red_cells:
        x = i * grid_size - grid_size/2
        y = j * grid_size - grid_size/2
        rect = Rectangle((x, y), grid_size, grid_size, 
                        facecolor='red', alpha=0.3, edgecolor='none')
        ax.add_patch(rect)
    
    # Cellules vertes (intersection)
    for (i, j) in green_cells:
        x = i * grid_size - grid_size/2
        y = j * grid_size - grid_size/2
        rect = Rectangle((x, y), grid_size, grid_size, 
                        facecolor='green', alpha=0.3, edgecolor='none')
        ax.add_patch(rect)
    
    # Courbes de référence (rouge)
    for ref_data in ref_curves:
        ref_x, ref_y = ref_data[:, 0], ref_data[:, 1]
        ax.plot(ref_x, ref_y, 'r-', linewidth=2, alpha=0.8)
    
    # Légende pour les courbes de référence
    ax.plot([], [], 'r-', linewidth=2, label='Courbe cible', alpha=0.8)
    
    # Courbe générée (bleue)
    ax.plot(traj_x, traj_y, 'b-', linewidth=1.5, label='Courbe générée', alpha=0.7)
    
    # Ajuster les limites
    all_ref_points = np.vstack(ref_curves)
    margin = 0.075
    #x_range = np.ptp(all_ref_points[:, 0])
    #y_range = np.ptp(all_ref_points[:, 1])
    #x_min = np.min(all_ref_points[:, 0]) - x_range * margin
    #x_max = np.max(all_ref_points[:, 0]) + x_range * margin
    #y_min = np.min(all_ref_points[:, 1]) - y_range * margin
    #y_max = np.max(all_ref_points[:, 1]) + y_range * margin
    x_min = -0.026
    x_max = 0.026
    y_min = -0.0045
    y_max = 0.0645
    
    ax.set_xlim(x_min, x_max)
    ax.set_ylim(y_min, y_max)
    ax.set_aspect('equal')
    ax.grid(True, alpha=0.3)
    ax.legend()
    ax.set_xlabel('x (m)', fontsize=12)
    ax.set_ylabel('y (m)', fontsize=12)
    ax.set_title(f'Précision = {n_green}/{n_green+n_red} = {precision:.4f}', 
                fontsize=14, fontweight='bold')
    
    plt.tight_layout()


